// ─── State ───────────────────────────────────────────────────────────────────
let currentLang = localStorage.getItem("mashriq_lang") || "en";

// ─── Helper ──────────────────────────────────────────────────────────────────
function t(key) {
  return translations[currentLang][key] || translations.en[key] || key;
}

// ─── Apply translations to every [data-i18n] element ─────────────────────────
function applyTranslations() {
  const lang = translations[currentLang];

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (lang[key] !== undefined) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = lang[key];
      } else if (el.tagName === "OPTION") {
        el.textContent = lang[key];
      } else {
        el.innerHTML = lang[key];
      }
    }
  });

  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const key = el.dataset.i18nPh;
    if (lang[key] !== undefined && (el.tagName === "INPUT" || el.tagName === "TEXTAREA")) {
      el.placeholder = lang[key];
    }
  });

  // RTL / LTR
  document.documentElement.setAttribute("dir", lang.dir);
  document.documentElement.setAttribute("lang", currentLang);

  // Update toggle button labels (desktop + mobile) to show the OTHER language
  document.querySelectorAll("#langToggle, #langToggleMob").forEach(btn => {
    // Preserve child icons (e.g. the globe <i> inside the button)
    const hasIcon = btn.querySelector("i");
    if (hasIcon) {
      let textNode = null;
      btn.childNodes.forEach(n => { if (n.nodeType === 3 && n.textContent.trim()) textNode = n; });
      if (textNode) { textNode.textContent = " " + lang.lang_toggle; }
      else { btn.appendChild(document.createTextNode(" " + lang.lang_toggle)); }
    } else {
      btn.textContent = lang.lang_toggle;
    }
  });

  // Reset submit button text on lang switch
  document.querySelectorAll(".btn-submit").forEach(btn => {
    btn.textContent = lang.form_btn;
    btn.onclick = function () { this.textContent = lang.form_sent; };
  });

  // Persist choice
  localStorage.setItem("mashriq_lang", currentLang);

  // Notify dynamic components (JS-rendered carousels etc.)
  window.dispatchEvent(new CustomEvent("mashriq:langchange", { detail: { lang: currentLang } }));
}

// ─── Toggle ───────────────────────────────────────────────────────────────────
function toggleLanguage() {
  currentLang = currentLang === "en" ? "ar" : "en";
  applyTranslations();
}

// ─── Init ────────────────────────────────────────────────────────────────────
document.addEventListener("DOMContentLoaded", () => {
  applyTranslations();
  const lt = document.getElementById("langToggle");
  if (lt) lt.addEventListener("click", toggleLanguage);
  const ltm = document.getElementById("langToggleMob");
  if (ltm) ltm.addEventListener("click", toggleLanguage);
});
